	 *
	 * اگر افزونهٔ SearchWP Live Ajax Search فعال باشد (window.SearchWP)، این
	 * اسکریپت هیچ کاری نمی‌کند تا دو دراپ‌داون هم‌زمان باز نشود.
	 */
	function tara_search_inline_js() {
		if ( is_admin() ) {
			return;
		}

		/* v3.17.14 — چاپِ هوشمندترِ اسکریپتِ جست‌وجوی زنده.
		   ------------------------------------------------------------------
		   دو حالت که این اسکریپت هیچ کاری نمی‌کند و فقط ~۱۲KB به HTML
		   اضافه می‌کند:

		     ۱) خودِ SearchWP نصب است ⇒ خطِ اولِ اسکریپت با
		        `if (window.SearchWP …) return;` بیرون می‌زد، ولی متنش
		        هنوز دانلود و پارس می‌شد. اگر SearchWP فعال باشد این
		        اسکریپت اصلاً لازم نیست.
		     ۲) اگر هدرِ قالب خاموش شده باشد (TARA_HEADER_SEARCH=false)
		        هیچ `#lsds` ساخته نمی‌شود.

		   در حالت عادی (بدون SearchWP، با هدرِ پیش‌فرض) رفتار
		   دقیقاً مثل قبل است — چیزی از دست نمی‌رود. با فیلتر
		   `tara_search_inline_needed` می‌توان اجبار کرد. */
		$tara_search_needed = true;

		/* اگر SearchWP هست، کارِ این اسکریپت را آن انجام می‌دهد. */
		if ( defined( 'SEARCHWP_VERSION' ) || class_exists( 'SearchWP' ) ) {
			$tara_search_needed = false;
		}

		/* فیلترِ صریح برای خاموش/روشن کردن. */
		$tara_search_needed = (bool) apply_filters( 'tara_search_inline_needed', $tara_search_needed );
		if ( ! $tara_search_needed ) {
			return;
		}

		$endpoint = admin_url( 'admin-ajax.php' );
		$nonce    = wp_create_nonce( 'tara_search' );
		?>
		<script id="tara-search-inline">
		(function () {
			if (window.SearchWP || window.SearchWP_Live_Search) { return; }
			var inputs = [];
			var main = document.getElementById('lsds');
			var mob = document.getElementById('lsds_mobile');
			if (main) { inputs.push(main); }
			if (mob) { inputs.push(mob); }
			if (!inputs.length) { return; }

			var box = document.createElement('div');
			box.id = 'tara-search-results';
			box.setAttribute('role', 'listbox');
			box.setAttribute('aria-label', 'نتایج جست‌وجو');
			var host = main ? main.closest('#searches') || main.parentNode : mob.parentNode;
			host.appendChild(box);

			/* v3.8.3 — وضعیت برای صفحه‌خوان‌ها؛ خودِ لیست aria-live ندارد
			   تا هر تایپ دو بار خوانده نشود. */
			var status = document.createElement('span');
			status.className = 'screen-reader-text';
			status.setAttribute('role', 'status');
			status.setAttribute('aria-live', 'polite');
			host.appendChild(status);

			var timer = null;
			var seq = 0;
			var cache = {};
			var active = -1;
			var activeInput = null;
			var positionFrame = 0;

			/* پنجره زیر ورودی فعال است، نه الزاماً ورودی دسکتاپِ مخفی. */
			function useInput(input) {
				if (activeInput === input) { return; }
				window.clearTimeout(timer);
			close();
				activeInput = input;
				host = input.closest('#searches, #searches_mobile') || input.parentNode;
				host.appendChild(box);
				host.appendChild(status);
				box.style.left = '0px';
			}
			function positionBox() {
				if (positionFrame) { window.cancelAnimationFrame(positionFrame); }
				positionFrame = window.requestAnimationFrame(function () {
					positionFrame = 0;
					if (!box.classList.contains('is-open') || !box.getClientRects().length) { return; }
					/* ابتدا هم‌تراز با لبهٔ چپ فرم؛ سپس در هر دو سمت داخل صفحه. */
					box.style.left = '0px';
					var rect = box.getBoundingClientRect();
					var width = document.documentElement.clientWidth;
					if (!width) { return; }
					var shift = rect.left < 8 ? 8 - rect.left : (rect.right > width - 8 ? width - 8 - rect.right : 0);
					box.style.left = shift + 'px';
				});
			}
			window.addEventListener('resize', positionBox);

			function esc(s) {
				return String(s == null ? '' : s).replace(/[&<>"']/g, function (c) {
					return { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c];
				});
			}

			function close() {
				window.clearTimeout(timer);
				seq++;
				box.classList.remove('is-open');
				box.innerHTML = '';
				box.setAttribute('aria-busy', 'false');
				box.removeAttribute('aria-activedescendant');
				active = -1;
				for (var i = 0; i < inputs.length; i++) {
					inputs[i].setAttribute('aria-expanded', 'false');
					inputs[i].removeAttribute('aria-activedescendant');
				}
			}

			/* v3.8.3 — «محمولهٔ» تازه: تا پاسخ برسد، سه ردیفِ اسکلت با
			   ارتفاعِ ثابت نشان داده می‌شود تا کادر ناگهان نپرد. */
			function skeleton() {
				box.innerHTML = '<div class="tara-sr__head">در حال جست‌وجو…</div>'
					+ '<div class="tara-sr__row is-skeleton" aria-hidden="true"><span class="tara-sr__sk tara-sr__sk--img"></span><span class="tara-sr__sk-lines"><span class="tara-sr__sk"></span><span class="tara-sr__sk tara-sr__sk--sm"></span></span></div>'
					+ '<div class="tara-sr__row is-skeleton" aria-hidden="true"><span class="tara-sr__sk tara-sr__sk--img"></span><span class="tara-sr__sk-lines"><span class="tara-sr__sk"></span><span class="tara-sr__sk tara-sr__sk--sm"></span></span></div>'
					+ '<div class="tara-sr__row is-skeleton" aria-hidden="true"><span class="tara-sr__sk tara-sr__sk--img"></span><span class="tara-sr__sk-lines"><span class="tara-sr__sk"></span><span class="tara-sr__sk tara-sr__sk--sm"></span></span></div>';
				box.classList.add('is-open');
				positionBox();
				box.setAttribute('aria-busy', 'true');
			}

			function setActive(next) {
				var rows = box.querySelectorAll('a.tara-sr__row');
				if (!rows.length) { return; }
				if (active > -1 && rows[active]) {
					rows[active].classList.remove('is-active');
				}
				active = next;
				if (active < 0) { active = rows.length - 1; }
				if (active >= rows.length) { active = 0; }
				for (var i = 0; i < rows.length; i++) {
					var on = (i === active);
					rows[i].classList.toggle('is-active', on);
					rows[i].setAttribute('aria-selected', on ? 'true' : 'false');
				}
				var row = rows[active];
				if (row) {
					if (!row.id) { row.id = 'tara-sr-opt-' + active; }
					for (var j = 0; j < inputs.length; j++) {
						inputs[j].setAttribute('aria-activedescendant', row.id);
					}
					if (row.scrollIntoView) { row.scrollIntoView({ block: 'nearest' }); }
				}
			}

			function renderError(q) {
				active = -1;
				box.innerHTML = '<div class="tara-sr__empty tara-sr__empty--err" role="alert">جست‌وجو ناموفق بود. اتصال را بررسی کنید و دوباره تلاش کنید.'
					+ ' <button type="button" class="tara-sr__retry">تلاش دوباره</button></div>';
				box.classList.add('is-open');
				positionBox();
				box.setAttribute('aria-busy', 'false');
				status.textContent = 'جست‌وجو ناموفق بود.';
				var retry = box.querySelector('.tara-sr__retry');
				if (retry) {
					retry.addEventListener('click', function (ev) {
						/* دکمه با رندرِ اسکلت از DOM جدا می‌شود؛ بدون
						   توقفِ انتشار، شنوندهٔ کلیکِ document آن را «بیرون از
						   کادر» می‌بیند و پنجره را می‌بندد. */
						ev.stopPropagation();
						delete cache[q];
						ask(q);
					});
				}
			}

			function render(data, q) {
				var items = (data && data.items) || [];
				active = -1;
				if (!items.length) {
					box.innerHTML = '<div class="tara-sr__empty">چیزی برای «' + esc(q) + '» پیدا نشد.</div>';
					box.classList.add('is-open');
					positionBox();
					box.setAttribute('aria-busy', 'false');
					status.textContent = 'نتیجه‌ای پیدا نشد.';
					return;
				}
				var html = '<div class="tara-sr__head">' + (data && data.count > items.length ? 'نتایج جست‌وجو — ' + items.length + ' از ' + data.count : 'نتایج جست‌وجو') + '</div>';
				for (var i = 0; i < items.length; i++) {
					var it = items[i];
					html += '<a class="tara-sr__row" role="option" aria-selected="false" id="tara-sr-opt-' + i + '" href="' + esc(it.url) + '">'
						+ (it.cover ? '<img src="' + esc(it.cover) + '" width="40" height="40" alt="" loading="lazy" decoding="async">' : '')
						+ '<span><span class="tara-sr__t">' + esc(it.title) + '</span>'
						+ (it.artist ? '<span class="tara-sr__a">' + esc(it.artist) + '</span>' : '')
						+ (it.type ? '<span class="tara-sr__type">' + esc(it.type) + '</span>' : '')
						+ '</span></a>';
				}
				if (data && data.more) {
					html += '<a class="tara-sr__row tara-sr__row--more" role="option" aria-selected="false" href="' + esc(data.more) + '"><span class="tara-sr__t">همهٔ نتایج</span></a>';
				}
				box.innerHTML = html;
				box.classList.add('is-open');
				positionBox();
				box.setAttribute('aria-busy', 'false');
				status.textContent = items.length + ' نتیجه پیدا شد.';
			}

			function ask(value) {
				var q = String(value || '').trim();
				if (q.length < 2) { close(); return; }

				if (cache[q]) {
					render(cache[q], q);
					return;
				}

				var mine = ++seq;
				skeleton();

				var url = '<?php echo esc_url_raw( $endpoint ); ?>?action=tara_search&nonce=<?php echo esc_js( $nonce ); ?>&q=' + encodeURIComponent(q);
				var xhr = new XMLHttpRequest();
				xhr.open('GET', url, true);
				xhr.onreadystatechange = function () {
					if (xhr.readyState !== 4 || mine !== seq) { return; }
					var payload = null;
					try { payload = JSON.parse(xhr.responseText); } catch (e) { payload = null; }
					if (xhr.status !== 200 || !payload) {
						/* v3.16.0 — پیش از این خطا بی‌صدا پنجره را می‌بست و کاربر فکر
						   می‌کرد جست‌وجو «چیزی پیدا نکرد». حالا پیام + دکمهٔ تلاش. */
						renderError(q);
						return;
					}
					var data = payload && payload.data ? payload.data : { items: [] };
					cache[q] = data;
					render(data, q);
				};
				xhr.send();
			}

			inputs.forEach(function (input) {
				input.setAttribute('autocomplete', 'off');
				input.setAttribute('role', 'combobox');
				input.setAttribute('aria-autocomplete', 'list');
				input.setAttribute('aria-expanded', 'false');
				input.setAttribute('aria-controls', 'tara-search-results');
				input.setAttribute('aria-haspopup', 'listbox');

				input.addEventListener('input', function () {
					useInput(input);
					var v = input.value;
					seq++; /* پاسخِ عبارت پیشین پس از تایپ تازه معتبر نیست. */
					input.setAttribute('aria-expanded', v.trim().length >= 2 ? 'true' : 'false');
					window.clearTimeout(timer);
					/* v3.8.3 — ۲۵۰ms: هم تایپِ سریع را دست‌نخورده می‌گذارد و
					   هم نسبت به ۲۶۰ms قبلی یک درخواست کمتر می‌فرستد. */
					timer = window.setTimeout(function () { ask(v); }, 250);
				});

				input.addEventListener('keydown', function (ev) {
					var open = box.classList.contains('is-open');
					if (ev.key === 'Escape' || ev.keyCode === 27) {
						if (open) {
							ev.preventDefault();
							close();
						}
						return;
					}
					if (!open) { return; }
					if (ev.key === 'ArrowDown' || ev.keyCode === 40) {
						ev.preventDefault();
						setActive(active + 1);
					} else if (ev.key === 'ArrowUp' || ev.keyCode === 38) {
						ev.preventDefault();
						setActive(active - 1);
					} else if (ev.key === 'Enter' || ev.keyCode === 13) {
						var rows = box.querySelectorAll('a.tara-sr__row');
						if (active > -1 && rows[active]) {
							ev.preventDefault();
							window.location.href = rows[active].getAttribute('href');
						}
					}
				});

				input.addEventListener('focus', function () {
					useInput(input);
					if (input.value.trim().length >= 2 && box.innerHTML) {
						box.classList.add('is-open');
						positionBox();
					}
				});
			});

			document.addEventListener('click', function (ev) {
				var node = ev.target;
				if (!node || !node.closest) { return; }
				if (!box.contains(node) && !node.closest('#searches') && !node.closest('#mobiles_header')) {
					close();
				}
			});
		})();
		</script>
		<?php
	}
	add_action( 'wp_footer', 'tara_search_inline_js', 98 );
}
